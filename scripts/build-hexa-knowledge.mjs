/**
 * node scripts/build-hexa-knowledge.mjs
 *
 * Builds api/_lib/knowledge.js — the fact sheet the website assistant (Hexa,
 * api/hexa-chat.js) answers from. It is taken straight from the site content in
 * src/content/*, so Hexa never says anything the site does not say. Visual-only
 * fields (images, logos, colours, diagrams) are dropped to keep it compact.
 * Runs as the first step of `npm run build`; the output is committed so the
 * Vercel function always has it.
 */
import fs from 'node:fs/promises';
import { build } from 'esbuild';

const MODULES = ['site', 'home', 'officialLabs', 'sandboxes', 'labs', 'certifications', 'lms', 'pricing', 'training', 'about', 'contact'];

const entry = MODULES.map((m) => `export * as ${m} from './src/content/${m}.ts';`).join('\n');
const out = await build({
  stdin: { contents: entry, resolveDir: process.cwd(), loader: 'ts' },
  bundle: true,
  format: 'esm',
  platform: 'node',
  write: false,
  logLevel: 'silent',
  // Vite-only build settings read by src/content/site.ts.
  define: { 'import.meta.env': JSON.stringify({ VITE_SITE_URL: 'https://hexalabs.online', DEV: false, PROD: true }) },
});
const code = out.outputFiles[0].text;
const mod = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);

/** Keys that only drive visuals or internal wiring. */
const DROP = new Set([
  'image', 'illustration', 'imageAlt', 'images', 'logos', 'logo', 'icon', 'brandHex', 'officialLogo', 'markLogo',
  'logoAspect', 'wordmark', 'diagram', 'themes', 'accent', 'tint', 'color', 'colorFg', 'initials', 'requestType',
  'sitemap', 'priority', 'id', 'kind', 'tracedLearner', 'tracedTarget',
]);

function clean(value) {
  if (typeof value === 'function') return undefined;
  if (Array.isArray(value)) {
    const items = value.map(clean).filter((v) => v !== undefined && v !== '');
    return items.length ? items : undefined;
  }
  if (value && typeof value === 'object') {
    const res = {};
    for (const [k, v] of Object.entries(value)) {
      if (DROP.has(k)) continue;
      const c = clean(v);
      if (c !== undefined) res[k] = c;
    }
    return Object.keys(res).length ? res : undefined;
  }
  if (typeof value === 'string') return value.replace(/\s+/g, ' ').trim();
  return value;
}

const knowledge = {};
for (const m of MODULES) knowledge[m] = clean({ ...mod[m] });

// Certifications: keep the exam list compact (vendor, code, name, level).
if (Array.isArray(mod.certifications?.certifications)) {
  knowledge.certifications.certifications = mod.certifications.certifications.map((c) =>
    [c.vendor, c.code, c.name, c.level].filter(Boolean).join(' | '),
  );
}

await fs.mkdir('api/_lib', { recursive: true });
const json = JSON.stringify(knowledge);
await fs.writeFile(
  'api/_lib/knowledge.js',
  `// Generated by scripts/build-hexa-knowledge.mjs from src/content — do not edit.
export default ${json};
`,
);
console.log(`Hexa knowledge: ${(json.length / 1024).toFixed(1)} KB from ${MODULES.length} content files`);
